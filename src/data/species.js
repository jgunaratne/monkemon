const _speciesMap = new Map(CORE_SPECIES.map((s) => [s.id, s]));

export function registerForgedSpecies(entry) {
  if (!entry || !entry.id) return;
  const normalized = {
    ...entry,
    moves: entry.moves || ['monk_run', 'fake_out', 'eat_snack', 'sky_jump', 'kaiju_roar'],
    baseStats: entry.baseStats || { hp: 70, atk: 68, def: 64, spd: 66 },
    scale: entry.scale || 1.08,
    catchRate: entry.catchRate || 0.5,
  };
  _speciesMap.set(normalized.id, normalized);
}

export function getSpecies(id) {
  return _speciesMap.get(id) || CORE_SPECIES[0];
}

export function getAllSpecies() {
  return Array.from(_speciesMap.values()).sort((a, b) => (a.dexNum || 999) - (b.dexNum || 999));
}
